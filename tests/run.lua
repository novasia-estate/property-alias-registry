package.path = './lua/?.lua;./lua/?/init.lua;' .. package.path
local a=require('property_alias')
local n=0
local function test(name,fn)
  local ok,err=pcall(fn)
  if not ok then error('FAIL '..name..': '..tostring(err),0) end
  n=n+1;print('PASS '..name)
end
local function entry(id,label,scope)
  return {entity_id=id,alias=label,scope=scope or 'source:a',provenance='synthetic fixture'}
end
local function fails(fn) return not pcall(fn) end
test('ASCII whitespace and case',function() assert(a.normalize('  GARDEN\tCourt  ')=='garden court') end)
test('selected Unicode spaces and punctuation',function() assert(a.normalize('River—House  A')=='river-house a') end)
test('original multilingual query retained',function()
  local r=a.new({entry('A','การ์เดน คอร์ต')});local x=r:resolve('การ์เดน คอร์ต')
  assert(x.status=='resolved' and x.entity_id=='A' and x.query=='การ์เดน คอร์ต')
end)
test('Cyrillic aliases are explicit',function()
  local r=a.new({entry('A','Гарден Корт')});assert(r:resolve('Гарден Корт').entity_id=='A')
  assert(r:resolve('гарден корт').status=='unknown')
end)
test('Khmer text is preserved',function() local s='ផ្ទះ';assert(a.normalize(s)==s) end)
test('no transliteration invented',function() assert(a.new({entry('A','Garden Court')}):resolve('Гарден Корт').status=='unknown') end)
test('no fuzzy near-spelling merge',function() assert(a.new({entry('A','Garden Court')}):resolve('Garden Cort').status=='unknown') end)
test('similar Latin and Cyrillic glyphs remain distinct',function() assert(a.normalize('Court')~=a.normalize('Сourt')) end)
test('combining sequence is not silently NFC folded',function() assert(a.normalize('é')~=a.normalize('é')) end)
test('multiple identities in one scope stay ambiguous',function()
  local x=a.new({entry('A','River—House'),entry('B','River-House')}):resolve('river-house','source:a')
  assert(x.status=='ambiguous' and x.entity_id==nil and #x.candidates==2)
end)
test('scope disambiguates identical names',function()
  local r=a.new({entry('A','Court','source:a'),entry('B','Court','source:b')})
  assert(r:resolve('Court').status=='ambiguous' and r:resolve('Court','source:b').entity_id=='B')
end)
test('scope is case-sensitive',function() assert(a.new({entry('A','Court')}):resolve('Court','SOURCE:A').status=='unknown') end)
test('duplicate observations of same identity do not create ambiguity',function()
  local x=a.new({entry('A','Court'),entry('A','COURT')}):resolve('court');assert(x.status=='resolved' and #x.matches==2)
end)
test('unknown scope returns no candidate',function() assert(a.new({entry('A','Court')}):resolve('court','other').status=='unknown') end)
test('missing provenance rejects construction',function()
  local e=entry('A','Court');e.provenance=nil;assert(fails(function() a.new({e}) end))
end)
test('empty aliases and nonstring values reject',function()
  assert(not a.normalize('  '));assert(not a.normalize(123));assert(fails(function() a.new({entry('A',' ')}) end))
end)
test('UTF8 overlong sequence rejects',function() assert(select(2,a.normalize(string.char(192,175)))=='invalid_utf8') end)
test('UTF8 truncated sequence rejects',function() assert(select(2,a.normalize(string.char(226,128)))=='invalid_utf8') end)
test('UTF8 surrogate rejects',function() assert(select(2,a.normalize(string.char(237,160,128)))=='invalid_utf8') end)
test('UTF8 out-of-range codepoint rejects',function() assert(select(2,a.normalize(string.char(244,144,128,128)))=='invalid_utf8') end)
test('newline and bidi override reject',function()
  assert(select(2,a.normalize('Court\n'))=='control_character')
  assert(select(2,a.normalize('Court'..string.char(226,128,174)))=='bidi_control')
end)
test('invalid query returns a value instead of raising',function() assert(a.new({}):resolve('\0').status=='invalid') end)
test('oversized labels reject',function() assert(select(2,a.normalize(string.rep('a',4097)))=='label_exceeds_4096_bytes') end)
test('input and result mutation cannot change stored records',function()
  local e=entry('A','Court');local r=a.new({e});e.entity_id='B'
  local x=r:resolve('Court');x.matches[1].entity_id='C';x.candidates[1]='D'
  assert(r:resolve('Court').entity_id=='A')
end)
test('immutable extension leaves original registry unchanged',function()
  local r=a.new({entry('A','Court')});local s=r:with({entry('B','Court')})
  assert(r:resolve('Court').status=='resolved' and s:resolve('Court').status=='ambiguous')
end)
test('failed extension leaves original intact',function()
  local r=a.new({entry('A','Court')});assert(fails(function() r:with({entry('', 'Court')}) end));assert(r:resolve('Court').entity_id=='A')
end)
test('dense array contract rejects maps and holes',function()
  assert(fails(function() a.new({foo=entry('A','Court')}) end))
  assert(fails(function() a.new({[1]=entry('A','Court'),[3]=entry('B','Court')}) end))
end)
test('audit separates scoped conflicts from cross-scope ambiguity',function()
  local r=a.new(require('examples.catalogue'));local x=r:audit()
  assert(x.entry_count==6 and #x.scoped_conflicts==1 and #x.unscoped_ambiguities==2)
  x.scoped_conflicts[1].candidates[1]='changed';assert(r:resolve('River-House','demo:central').status=='ambiguous')
end)
print('Behavioral checks passed: '..n)

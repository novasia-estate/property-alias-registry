package.path='./lua/?.lua;./lua/?/init.lua;'..package.path
local aliases=require('property_alias')
local n=0
local function test(name,fn)local ok,e=pcall(fn);if not ok then error(name..': '..tostring(e),0)end;n=n+1;print('PASS '..name)end
local function e(id,label,scope,source)return {entity_id=id,alias=label,scope=scope or 'scope',provenance=source or 'synthetic source'}end
local function fails(fn)return not pcall(fn)end
test('withdraw only the explicitly selected observation',function()
 local a,b,c=e('A','Court','scope','old'),e('B','Court','scope','current'),e('A','Корт','scope','other')
 local old=aliases.new({a,b,c});local new,r=old:without({a})
 assert(new:resolve('Court','scope').entity_id=='B' and new:resolve('Корт','scope').entity_id=='A')
 assert(old:resolve('Court','scope').status=='ambiguous' and r.removed_count==1 and r.matched_selectors==1)
end)
test('scope is part of the withdrawal identity',function()
 local a=e('A','Court','one');local old=aliases.new({a,e('A','Court','two')});local new=old:without({a})
 assert(new:resolve('Court','one').status=='unknown' and new:resolve('Court','two').status=='resolved')
end)
test('provenance is part of the withdrawal identity',function()
 local a=e('A','Court','scope','first');local new=aliases.new({a,e('A','Court','scope','second')}):without({a})
 assert(#new:entries()==1 and new:entries()[1].provenance=='second')
end)
test('normalized key equality never substitutes for exact authored alias',function()
 local new,r=aliases.new({e('A','Court')}):without({e('A','COURT')})
 assert(new:resolve('court').status=='resolved' and r.removed_count==0 and #r.unmatched_entries==1)
end)
test('identical repeated observations are all removed and counted',function()
 local a=e('A','Court');local new,r=aliases.new({a,a,a}):without({a})
 assert(#new:entries()==0 and r.removed_count==3 and r.matched_selectors==1)
end)
test('unmatched selectors are explicit and preserve request order',function()
 local new,r=aliases.new({}):without({e('A','One'),e('B','Two')})
 assert(r.requested_count==2 and r.matched_selectors==0 and r.unmatched_entries[2].alias=='Two')
end)
test('duplicate selectors reject the whole operation',function()
 local a=e('A','Court');local old=aliases.new({a});assert(fails(function()old:without({a,a})end));assert(#old:entries()==1)
end)
test('invalid later selector cannot partially mutate original',function()
 local a=e('A','Court');local old=aliases.new({a});local bad=e('B','Other');bad.provenance=nil
 assert(fails(function()old:without({a,bad})end) and old:resolve('Court').status=='resolved')
end)
test('report, selector and returned registry are isolated copies',function()
 local a=e('A','Court');local old=aliases.new({a});local new,r=old:without({e('B','Other')})
 r.unmatched_entries[1].alias='changed';a.alias='changed';local out=new:entries();out[1].alias='changed'
 assert(old:resolve('Court').status=='resolved' and new:resolve('Court').status=='resolved')
end)
test('length-prefixed tuples cannot collide through delimiter injection',function()
 local a,b=e('A','x:scope','scope','p'),e('A:x','scope','scope','p')
 local new=aliases.new({a,b}):without({a});assert(#new:entries()==1 and new:entries()[1].entity_id=='A:x')
end)
test('empty withdrawal and empty registry are valid',function()
 local new,r=aliases.new({}):without({});assert(#new:entries()==0 and r.requested_count==0)
 local kept=aliases.new({e('A','Court')}):without({});assert(#kept:entries()==1)
end)
test('invalid UTF8 and sparse arrays reject',function()
 local old=aliases.new({});assert(fails(function()old:without({e('A',string.char(192,175))})end))
 assert(fails(function()old:without({[2]=e('A','Court')})end))
end)
test('id scope and provenance edge rules remain the construction contract',function()
 local new,r=aliases.new({e(' A ','Court',' scope ',' source ')}):without({e('A','Court','scope','source')})
 assert(r.removed_count==1 and #new:entries()==0)
end)
test('conflict audit is recomputed without deleting unrelated aliases',function()
 local a=e('A','Court');local new=aliases.new({a,e('B','Court'),e('C','Other')}):without({a})
 assert(#new:audit().scoped_conflicts==0 and #new:audit().unscoped_ambiguities==0 and new:audit().entry_count==2)
end)
test('withdrawal results compose with immutable extension',function()
 local a=e('A','Court');local new=aliases.new({a}):without({a});local extended=new:with({e('B','Court')})
 assert(new:resolve('Court').status=='unknown' and extended:resolve('Court').entity_id=='B')
end)
print('Withdrawal: '..n..' behavioral checks passed')
